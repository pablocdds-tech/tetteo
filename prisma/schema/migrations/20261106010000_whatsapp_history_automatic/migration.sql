CREATE TABLE "av_channel_history_recent_sync" (
  "id" TEXT NOT NULL,
  "organizationId" TEXT NOT NULL,
  "storeId" TEXT NOT NULL,
  "accountId" TEXT NOT NULL,
  "revision" INTEGER NOT NULL,
  "requestedById" TEXT NOT NULL,
  "requestId" TEXT NOT NULL,
  "state" TEXT NOT NULL DEFAULT 'RUNNING',
  "nextPage" INTEGER NOT NULL DEFAULT 1,
  "pageSize" INTEGER NOT NULL DEFAULT 100,
  "pagesProcessed" INTEGER NOT NULL DEFAULT 0,
  "since" TIMESTAMP(3) NOT NULL,
  "until" TIMESTAMP(3) NOT NULL,
  "startedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "finishedAt" TIMESTAMP(3),
  "lastSyncedAt" TIMESTAMP(3),
  "importedConversations" INTEGER NOT NULL DEFAULT 0,
  "importedMessages" INTEGER NOT NULL DEFAULT 0,
  "skippedMessages" INTEGER NOT NULL DEFAULT 0,
  "coverageFrom" TIMESTAMP(3),
  "coverageUntil" TIMESTAMP(3),
  "complete" BOOLEAN NOT NULL DEFAULT false,
  "limitReason" TEXT,
  "error" TEXT,
  "leaseOwner" TEXT,
  "leaseUntil" TIMESTAMP(3),
  "attempts" INTEGER NOT NULL DEFAULT 0,
  "lastPageHash" TEXT,
  "createdAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "updatedAt" TIMESTAMP(3) NOT NULL,
  CONSTRAINT "av_channel_history_recent_sync_pkey" PRIMARY KEY ("id"),
  CONSTRAINT "av_history_recent_state" CHECK ("state" IN ('RUNNING','COMPLETE','PARTIAL','FAILED')),
  CONSTRAINT "av_history_recent_lease_pair" CHECK (("leaseOwner" IS NULL) = ("leaseUntil" IS NULL)),
  CONSTRAINT "av_history_recent_bounds" CHECK ("revision" > 0 AND "nextPage" > 0 AND "pageSize" BETWEEN 1 AND 100 AND "pagesProcessed" >= 0 AND "attempts" BETWEEN 0 AND 3 AND "since" <= "until" AND "importedConversations" >= 0 AND "importedMessages" >= 0 AND "skippedMessages" >= 0),
  CONSTRAINT "av_history_recent_scope_fkey" FOREIGN KEY ("organizationId","storeId","accountId") REFERENCES "AvChannelAccount"("organizationId","storeId","id") ON DELETE RESTRICT ON UPDATE CASCADE
